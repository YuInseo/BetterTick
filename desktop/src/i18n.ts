export function tr(text: string): string {
  if (language === "ko") return text;
  const key = text.trim().replace(/\s+/g, " ");
  return (
    (text.startsWith(" ") ? " " : "") +
    (english[key] ?? key) +
    (text.endsWith(" ") ? " " : "")
  );
}
